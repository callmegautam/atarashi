import type { GenerationPlan, PlannedFile } from '@atarashi/schema';
import { loadBaseline } from '../baseline.js';
import { buildEngineDeps, cliVersion } from '../engine.js';
import { reportError } from '../errors.js';
import { EXIT } from '../exit-codes.js';
import { Printer } from '../output.js';
import {
    CONFIG_FILE,
    diskReader,
    pinnedDeps,
    plan,
    readProjectConfig,
    specFromConfig,
    unverifiedBlueprints,
} from '../project.js';
import { reconcile } from '../reconcile.js';
import { buildRegistry } from '../registry-context.js';
import { readUserConfig, resolveConfigPath } from '../user-config.js';
import { targetSpecFor, versionChanges } from './update.js';

export interface StatusFlags {
    json?: boolean;
    offline?: boolean;
    registry?: string;
    color?: boolean;
}

export type DriftKind = 'modified' | 'missing' | 'unknown';

export interface Drift {
    path: string;
    kind: DriftKind;
}

/** Every generated file whose disk copy no longer matches the render it came from. */
export function findDrift(
    base: PlannedFile[],
    read: (path: string) => Buffer | undefined,
    unverified: ReadonlySet<string>
): Drift[] {
    const drift: Drift[] = [];
    for (const file of base) {
        if (file.path === CONFIG_FILE) continue;
        const onDisk = read(file.path);
        if (onDisk === undefined) {
            drift.push({ path: file.path, kind: 'missing' });
            continue;
        }
        const expected = Buffer.isBuffer(file.contents)
            ? file.contents
            : Buffer.from(file.contents, 'utf8');
        if (onDisk.equals(expected)) continue;
        const trusted = !file.sources.some((source) => unverified.has(source));
        drift.push({ path: file.path, kind: trusted ? 'modified' : 'unknown' });
    }
    return drift;
}

const DRIFT_LABEL: Record<DriftKind, string> = {
    modified: 'M',
    missing: 'D',
    unknown: '?',
};

export async function runStatus(flags: StatusFlags): Promise<number> {
    const cwd = process.cwd();
    const printer = new Printer({
        json: Boolean(flags.json),
        quiet: false,
        verbose: false,
        color: flags.color !== false && !flags.json,
    });

    try {
        const config = await readProjectConfig(cwd);
        const userConfig = await readUserConfig(resolveConfigPath());
        const registry = buildRegistry(
            { cwd, offline: flags.offline, registry: flags.registry },
            userConfig
        );
        const deps = buildEngineDeps(registry, { hooks: true, interactive: false });
        const read = diskReader(cwd);

        const baseline = await loadBaseline({
            cwd,
            atarashiVersion: config.atarashiVersion,
            runningVersion: cliVersion(),
            current: registry,
            offline: flags.offline,
        }).catch(() => undefined);

        // Without the original blueprints, the closest stand-in is the current
        // ones at the recorded answers. It is said so, not passed off as exact.
        const base: GenerationPlan = await plan(
            specFromConfig(config),
            pinnedDeps(deps, config, baseline?.registry ?? registry)
        );
        const unverified = baseline ? unverifiedBlueprints(config, base) : new Set<string>();
        const drift = findDrift(base.files, read, unverified);

        const targetDeps = pinnedDeps(deps, config, registry, cliVersion());
        const target = await plan(await targetSpecFor(config, targetDeps), targetDeps);
        const versions = versionChanges(config, target);
        const pending = reconcile({ base: base.files, target: target.files, read, unverified })
            .filter((change) => change.path !== CONFIG_FILE && change.kind !== 'unchanged')
            .map(({ path, kind }) => ({ path, kind }));

        const recorded = config.blueprints.map((blueprint) => {
            const available = target.summary.blueprints.find((entry) => entry.id === blueprint.id);
            return {
                id: blueprint.id,
                version: blueprint.version,
                available: available?.version ?? null,
            };
        });
        const clean = drift.length === 0 && pending.length === 0 && versions.length === 0;

        if (printer.options.json) {
            printer.emitJson({
                ok: true,
                name: config.name,
                atarashiVersion: config.atarashiVersion,
                runningVersion: cliVersion(),
                exactBaseline: Boolean(baseline),
                blueprints: recorded,
                versions,
                drift,
                update: pending,
                clean,
            });
            return EXIT.OK;
        }

        printer.line(
            `${config.name}: generated by atarashi ${config.atarashiVersion}, running ${cliVersion()}`
        );
        printer.line('');
        printer.line('Blueprints');
        const width = Math.max(...recorded.map((entry) => entry.id.length), 0);
        for (const entry of recorded) {
            const newer =
                entry.available && entry.available !== entry.version ? ` → ${entry.available}` : '';
            printer.line(`  ${entry.id.padEnd(width)}  ${entry.version}${newer}`);
        }
        for (const change of versions.filter((candidate) => candidate.from === null)) {
            printer.line(`  ${change.id.padEnd(width)}  ${change.to} (new requirement)`);
        }

        printer.line('');
        if (!baseline) {
            printer.warn(
                `The blueprints from atarashi ${config.atarashiVersion} are unavailable offline; edits below are measured against the current ones`
            );
        }
        if (drift.length === 0) {
            printer.line('Files: no changes since generation');
        } else {
            printer.line(`Files changed since generation (${drift.length})`);
            for (const entry of drift) printer.line(`  ${DRIFT_LABEL[entry.kind]} ${entry.path}`);
        }

        printer.line('');
        if (pending.length === 0 && versions.length === 0) {
            printer.success('Up to date');
        } else {
            printer.line(
                `\`atarashi update\` would touch ${pending.length} file(s); preview it with \`atarashi update --dry-run\``
            );
        }
        return EXIT.OK;
    } catch (thrown) {
        return reportError(printer, thrown);
    }
}
